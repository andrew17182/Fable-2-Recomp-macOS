#!/usr/bin/env python3
"""Version of this checkout: VERSION.txt plus the short git commit.

  python3 tools/fable2_version.py               -> 0.1.0 (c0b9d4a)
  python3 tools/fable2_version.py --json        -> {"version": ..., "git_sha": ..., "string": ...}
  python3 tools/fable2_version.py --header OUT  -> C header with FABLE2_VERSION, FABLE2_GIT_SHA,
                                                   FABLE2_VERSION_STRING (rewritten only on change)

The commit gets a "-dirty" suffix when tracked files have uncommitted changes (submodules
ignored). A GitHub ZIP (no git history) takes the commit from tools/fable2_archive_commit.txt, which git archive
fills in (.gitattributes export-subst); a copy with neither reports "0.1.0 (source)".
Runs under Python 3.9.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def _git(*args):
    return subprocess.run(['git', '-C', str(ROOT), *args], capture_output=True, text=True,
                          timeout=20, check=True).stdout.strip()


def info(root=ROOT):
    version = (root / 'VERSION.txt').read_text().strip()
    sha = ''
    try:
        # Only this checkout's own history (not a parent repository it was unpacked into).
        if Path(_git('rev-parse', '--show-toplevel')).resolve() == root.resolve():
            sha = _git('rev-parse', '--short=7', 'HEAD')
            if _git('status', '--porcelain', '--untracked-files=no', '--ignore-submodules=all'):
                sha += '-dirty'
    except (OSError, subprocess.SubprocessError):
        sha = ''
    archive = root / 'tools/fable2_archive_commit.txt'  # export-subst: a GitHub ZIP download has the commit here
    if not sha and archive.is_file():
        text = archive.read_text().strip()
        if text and not text.startswith('$Format'): sha = text[:7]
    stamp = root / '.fable2-version.json'  # written by tools/fable2_release.py into the release kit (no git there)
    if not sha and stamp.is_file():
        try:
            sha = json.loads(stamp.read_text()).get('git_sha', '') or ''
        except ValueError:
            sha = ''
    return {'version': version, 'git_sha': sha,
            'string': '%s (%s)' % (version, sha or 'source')}


def header(values):
    def q(text):
        return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'
    return ('// Generated by tools/fable2_version.py from VERSION.txt and git - do not edit.\n'
            '#pragma once\n'
            '#define FABLE2_VERSION %s\n'
            '#define FABLE2_GIT_SHA %s\n'
            '#define FABLE2_VERSION_STRING %s\n') % (q(values['version']), q(values['git_sha']),
                                                     q(values['string']))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--json', action='store_true')
    ap.add_argument('--header', type=Path)
    args = ap.parse_args()
    values = info()
    if args.header:
        text = header(values)
        try:
            unchanged = args.header.read_text() == text
        except OSError:
            unchanged = False
        if not unchanged:
            args.header.parent.mkdir(parents=True, exist_ok=True)
            args.header.write_text(text)
            print('[version] ' + values['string'], flush=True)
    elif args.json:
        print(json.dumps(values))
    else:
        print(values['string'])


if __name__ == '__main__':
    sys.exit(main())

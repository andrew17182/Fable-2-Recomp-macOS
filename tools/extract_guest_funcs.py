#!/usr/bin/env python3
"""Copy recompiled guest functions out of generated/default/*.cpp into one C++ include file for a build-time test.

    extract_guest_funcs.py --gen generated/default --out OUT.inc [--rename OLD=NEW ...] NAME [NAME ...]

Each DEFINE_REX_FUNC(NAME) body is emitted as a plain extern "C" function NAME (or NEW when renamed). Every function
the bodies call is declared; the __savegprlr_N / __restgprlr_N helpers they use are extracted too. Generated code
is game-derived and never committed: the test build makes this file in its build folder (tests/inflate_fast_tests.cpp).
Runs under /usr/bin/python3 3.9.
"""
import argparse
import re
import sys
from pathlib import Path

DEF = re.compile(r'^DEFINE_REX_FUNC\(([A-Za-z_][A-Za-z0-9_]*)\) \{$')
CALL = re.compile(r'\b([A-Za-z_][A-Za-z0-9_]*)\(ctx, base\)')
HELPER = re.compile(r'^__(save|rest)(gpr|fpr|vmx)lr_\d+$|^__(save|rest)(gpr|fpr|vmx)_\d+$')


def index_bodies(gen, wanted):
    """{name: body text} for the wanted names, scanning the recomp sources once."""
    found = {}
    for path in sorted(Path(gen).glob('fable_2_recomp.*.cpp')):
        lines = None
        with open(path, encoding='utf-8', errors='replace') as f:
            text = f.read()
        if not any(('DEFINE_REX_FUNC(%s)' % w) in text for w in wanted if w not in found):
            continue
        lines = text.split('\n')
        i = 0
        while i < len(lines):
            m = DEF.match(lines[i])
            if m and m.group(1) in wanted and m.group(1) not in found:
                j = i + 1
                while j < len(lines) and lines[j] != '}':
                    j += 1
                found[m.group(1)] = '\n'.join(lines[i + 1:j])
                i = j
            i += 1
        if len(found) == len(wanted):
            break
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gen', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--rename', action='append', default=[])
    ap.add_argument('names', nargs='+')
    a = ap.parse_args()
    rename = dict(r.split('=', 1) for r in a.rename)
    wanted = set(a.names)
    bodies = index_bodies(a.gen, wanted)
    # Pull in the register save/restore helpers the bodies call (repeat: helpers call nothing else).
    helpers = set()
    for b in bodies.values():
        helpers |= {c for c in CALL.findall(b) if HELPER.match(c)}
    if helpers - set(bodies):
        bodies.update(index_bodies(a.gen, helpers - set(bodies)))
    missing = (wanted | helpers) - set(bodies)
    if missing:
        sys.exit('extract_guest_funcs: not found in %s: %s' % (a.gen, ', '.join(sorted(missing))))
    called = set()
    for b in bodies.values():
        called |= set(CALL.findall(b))
    out = ['// Generated by tools/extract_guest_funcs.py from %s. Game-derived: build folder only, never commit.'
           % a.gen, '']
    for c in sorted(called | set(bodies) | set(rename.values())):
        out.append('extern "C" void %s(PPCContext& __restrict ctx, uint8_t* base);' % c)
    out.append('')
    for name in a.names + sorted(helpers):
        out.append('extern "C" void %s(PPCContext& __restrict ctx, uint8_t* base) {' % rename.get(name, name))
        out.append(bodies[name])
        out.append('}')
        out.append('')
    text = '\n'.join(out)
    p = Path(a.out)
    if not p.exists() or p.read_text() != text:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


if __name__ == '__main__':
    main()

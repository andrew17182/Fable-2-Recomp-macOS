// In-game message bridge: show host text through the game's own on-screen
// message system (GUI.DisplayInfoBoxParams, the timed button-less info box).
//
// Entry point (any thread):
//   uint32_t seq = fable2::gamemsg::Request("Turbo 2x on", 2.0);
//   ... later: fable2::gamemsg::Poll(ticket) -> kPending / kShown / kDeclined / kFailed
//
// How it works (docs/turbo.md, "In-game messages"):
//   1. The host writes the text into data/scripts/recomp/recomp_notify_text.lua
//      (always exactly 512 bytes, so a VFS that sized the file at boot still reads
//      all of it), as `return [==[text]==], lifetime`.
//   2. It queues scripts/recomp/recomp_notify.lua through the F6 mechanism
//      (fable2::f5lua::request_script): the next MainRenderLoop frame calls the
//      game's CScriptManager::RunScript on the guest main thread. No guest code
//      runs on the host UI thread.
//   3. recomp_notify.lua gates on normal gameplay (hero present, no fade/loading,
//      no other UI active), calls GUI.DisplayInfoBoxParams with the literal text,
//      and acks by RunScript-ing recomp_notify_shown.lua or
//      recomp_notify_declined.lua; the RunScript dispatcher probe counts those.
// The scripts are staged from src/lua/ by the build (fable_2_lua_staging), which
// also lists them in data/dir.manifest.
#pragma once

#include <atomic>
#include <chrono>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <mutex>
#include <string>
#include <system_error>

#include "fable2_f5_lua.h"

namespace fable2::gamemsg {

inline constexpr size_t kSlotSize = 512;
inline constexpr const char* kScript = "scripts/recomp/recomp_notify.lua";

inline std::filesystem::path& DataRoot() {
  static std::filesystem::path root;  // <game_data_root>/data
  return root;
}

inline void SetGameDataRoot(const std::filesystem::path& game_data_root) {
  DataRoot() = game_data_root / "data";
}

// True when a request can be dispatched at all (the RunScript callable has been
// captured and the message slot exists). Gameplay gating happens in Lua.
inline bool Available() {
  if (!fable2::f5lua::g_this.load() || !fable2::f5lua::g_method.load()) return false;
  std::error_code ec;
  return !DataRoot().empty() &&
         std::filesystem::is_regular_file(DataRoot() / "scripts/recomp/recomp_notify.lua", ec);
}

enum class Status { kPending, kShown, kDeclined, kFailed };

struct Ticket {
  uint32_t seq = 0;
  uint32_t shown0 = 0, declined0 = 0;
  std::chrono::steady_clock::time_point started{};
};

inline bool WriteSlot(const std::string& text, double lifetime) {
  std::string t = text.substr(0, 400);
  for (auto& c : t) {
    if (c == ']') c = ')';  // keeps the long-bracket string closed only by us
  }
  char tail[32];
  std::snprintf(tail, sizeof(tail), "]==], %.2f\n", lifetime);
  std::string body = "-- generated by the host (src/core/fable2_game_message.h)\nreturn [==[" + t + tail;
  if (body.size() + 2 > kSlotSize) return false;
  body += std::string(kSlotSize - body.size() - 1, '-');
  body += '\n';
  // Written in place (no temp file: anything new under data/ would be picked up
  // by the dir.manifest self-heal). The guest only reads it after Request()
  // queues the script, i.e. after this write has completed.
  std::ofstream out(DataRoot() / "scripts/recomp/recomp_notify_text.lua",
                    std::ios::binary | std::ios::trunc);
  if (!out) return false;
  out.write(body.data(), std::streamsize(body.size()));
  out.flush();
  return bool(out);
}

// Queues the message. Returns false (nothing queued) when the bridge is not
// available; the caller then shows its own overlay.
inline bool Request(const std::string& text, double lifetime, Ticket& ticket) {
  if (!Available() || !WriteSlot(text, lifetime)) return false;
  ticket.shown0 = fable2::f5lua::g_notify_shown.load();
  ticket.declined0 = fable2::f5lua::g_notify_declined.load();
  ticket.started = std::chrono::steady_clock::now();
  ticket.seq = fable2::f5lua::request_script(kScript);
  return true;
}

// Outcome of a request. kFailed covers "RunScript could not be called" and
// "no ack within `timeout`" (e.g. the main loop is stalled by a load).
inline Status Poll(const Ticket& ticket,
                   std::chrono::milliseconds timeout = std::chrono::milliseconds(1500)) {
  using fable2::f5lua::g_notify_declined;
  using fable2::f5lua::g_notify_shown;
  if (fable2::f5lua::g_script_fail_seq.load() == ticket.seq) return Status::kFailed;
  if (g_notify_shown.load() != ticket.shown0) return Status::kShown;
  if (g_notify_declined.load() != ticket.declined0) return Status::kDeclined;
  if (std::chrono::steady_clock::now() - ticket.started > timeout) return Status::kFailed;
  return Status::kPending;
}

inline const char* StatusName(Status s) {
  switch (s) {
    case Status::kPending: return "pending";
    case Status::kShown: return "shown";
    case Status::kDeclined: return "declined";
    default: return "failed";
  }
}

}  // namespace fable2::gamemsg
